import assert from 'node:assert/strict';
import {readFileSync,writeFileSync} from 'node:fs';
import {join} from 'node:path';
import {LOCAL,assertRemoteIdentity} from './staging-control.mjs';
import {http,success} from './remote-client.mjs';
await assertRemoteIdentity();
const token=readFileSync(join(LOCAL,'staging-access-jwt.txt'),'utf8').trim();
const headers={'Cf-Access-Jwt-Assertion':token,Cookie:'CF_Authorization='+token};
const before=await success('admin',{op:'state'}),tests=[];
const list=await http('admin','/admin/api/reports?status=all',undefined,headers);
assert.equal(list.status,200);assert.equal(list.body.ok,true);assert.equal(list.body.reports.length,21);
tests.push({name:'real Cloudflare Access authenticated administrator HTTP list',result:'PASS',status:list.status,rows:list.body.reports.length});
const denied=await http('admin','/admin/api/reports?status=all');assert.notEqual(denied.status,200);
tests.push({name:'administrator request without Access credentials denied',result:'PASS',status:denied.status});
const mutation=await http('admin','/admin/api/reports/00000000-0000-4000-8000-000000000001',{action:'reject'},headers);
assert.equal(mutation.status,503);assert.equal(mutation.headers['retry-after'],'60');assert.equal(mutation.body.error.code,'WRITE_MAINTENANCE');
tests.push({name:'authenticated administrator mutation maintenance503 Retry-After60',result:'PASS',status:503,retryAfter:'60'});
const pub=await http('public','/reports',{non_breeding_confirmed:true});assert.equal(pub.status,503);assert.equal(pub.headers['retry-after'],'60');
tests.push({name:'public POST maintenance503 Retry-After60',result:'PASS',status:503,retryAfter:'60'});
const get=await http('public','/reports/approved');assert.equal(get.status,200);assert.equal(get.body.ok,true);
tests.push({name:'legacy public GET available during maintenance',result:'PASS',status:200});
const after=await success('admin',{op:'state'});assert.equal(after.digest,before.digest);
tests.push({name:'all authenticated read/denied-write smoke requests leave D1 unchanged',result:'PASS',before:before.counts,after:after.counts});
writeFileSync(join(LOCAL,'access-maintenance-smoke.json'),JSON.stringify({at:new Date().toISOString(),tests},null,2)+'\n');
console.log(JSON.stringify({passed:tests.length,tests:tests.map(t=>t.name),token_printed:false}));
